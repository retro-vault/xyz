#!/usr/bin/env python3

from __future__ import annotations

import shutil
import textwrap
from pathlib import Path


ROOT = Path(__file__).resolve().parent
GENERATED = ROOT / "generated"
EXPECTED = ROOT / "expected.csv"

FAMILY_CONFIGS = {
    "rle_short": {
        "seed_base": 0x8100,
        "n_base": 18,
        "n_step": 3,
        "run_mask": 1,
        "thresh_base": 3,
        "thresh_span": 3,
    },
    "rle_mixed": {
        "seed_base": 0x9100,
        "n_base": 18,
        "n_step": 3,
        "run_mask": 3,
        "thresh_base": 3,
        "thresh_span": 3,
    },
    "rle_dense": {
        "seed_base": 0xA100,
        "n_base": 24,
        "n_step": 3,
        "run_mask": 1,
        "thresh_base": 1,
        "thresh_span": 3,
    },
    "rle_wide": {
        "seed_base": 0xB100,
        "n_base": 24,
        "n_step": 3,
        "run_mask": 3,
        "thresh_base": 5,
        "thresh_span": 3,
    },
}

FAMILY_NAMES = list(FAMILY_CONFIGS)
VARIANTS_PER_FAMILY = 10


def u8(value: int) -> int:
    return value & 0xFF


def u16(value: int) -> int:
    return value & 0xFFFF


def step(state: int) -> int:
    return u16(state * 25173 + 13849)


def rand8(state: int, salt: int) -> tuple[int, int]:
    state = step(u16(state + salt + 1))
    mixed = u16(state)
    mixed = u16(mixed ^ (mixed >> 7))
    mixed = u16(mixed ^ (mixed >> 3))
    return state, u8(mixed)


def rotl5(value: int) -> int:
    value = u16(value)
    return u16((value << 5) | (value >> 11))


def mix(acc: int, value: int) -> int:
    acc = u16(acc ^ u16(value + 0x9E37))
    acc = rotl5(acc)
    acc = u16(acc + (value ^ 0x7F4A))
    return acc


def render_case(name: str, body: str, defines: dict[str, int], expected: int) -> str:
    define_lines = "\n".join(f"#define {key} {value}u" for key, value in defines.items())
    return textwrap.dedent(
        f"""\
        /*
         * Generated by generate_portable_benchmarks.py.
         * Benchmark: {name}
         */
        #include "../../include/portable_bench.h"

        {define_lines}
        #define EXPECTED_CHECKSUM {expected}u

        int
        main(void)
        {{
        {textwrap.indent(body.rstrip(), "    ")}
        }}
        """
    )


def family_params(family: str, variant: int) -> dict[str, int]:
    cfg = FAMILY_CONFIGS[family]
    return {
        "N": cfg["n_base"] + (variant % 5) * cfg["n_step"],
        "RUN_MASK": cfg["run_mask"],
        "THRESH": cfg["thresh_base"] + (variant % cfg["thresh_span"]),
        "SEED": u16(cfg["seed_base"] + variant * 181),
    }


def generate_run_data(params: dict[str, int]) -> list[int]:
    data = [0] * params["N"]
    state = params["SEED"]
    current = 1 + ((params["SEED"] >> 1) & 7)
    i = 0

    while i < params["N"]:
        state, raw_run = rand8(state, 0x81 + i)
        state, raw_delta = rand8(state, 0xA1 + i)
        run = 1 + (raw_run & params["RUN_MASK"])
        delta = 1 + (raw_delta & params["THRESH"])
        current = u8(current + delta)
        for _ in range(run):
            if i >= params["N"]:
                break
            data[i] = current
            i += 1
    return data


def iter_runs(data: list[int]):
    i = 0
    n = len(data)
    while i < n:
        value = data[i]
        run = 1
        i += 1
        while i < n and data[i] == value:
            run += 1
            i += 1
        yield value, run


def rle_expected(params: dict[str, int]) -> int:
    data = generate_run_data(params)
    acc = mix(params["SEED"], params["N"] | (params["RUN_MASK"] << 8))
    acc = mix(acc, params["THRESH"])
    for value, run in iter_runs(data):
        acc = mix(acc, value | (run << 8))
    return acc


def rle_source(name: str, params: dict[str, int], expected: int) -> str:
    body = """\
static pb_u8 data[N];
pb_u8 i;
pb_u8 current;
pb_u16 state;
pb_u16 acc;

state = (pb_u16)SEED;
i = 0u;
current = (pb_u8)(1u + (((pb_u16)SEED >> 1) & 7u));
while (i < (pb_u8)N) {
    pb_u8 run;
    pb_u8 delta;
    pb_u8 j;

    run = (pb_u8)(1u + (pb_rand8(&state, (pb_u8)(0x81u + i)) & (pb_u8)RUN_MASK));
    delta = (pb_u8)(1u + (pb_rand8(&state, (pb_u8)(0xA1u + i)) & (pb_u8)THRESH));
    current = (pb_u8)(current + delta);
    for (j = 0u; j < run; ++j) {
        if (i >= (pb_u8)N)
            break;
        data[i] = current;
        i = (pb_u8)(i + 1u);
    }
}

acc = pb_mix((pb_u16)SEED, (pb_u16)(N | ((pb_u16)RUN_MASK << 8)));
acc = pb_mix(acc, (pb_u16)THRESH);
i = 0u;
while (i < (pb_u8)N) {
    pb_u8 value;
    pb_u8 run;

    value = data[i];
    run = 1u;
    i = (pb_u8)(i + 1u);
    while (i < (pb_u8)N && data[i] == value) {
        run = (pb_u8)(run + 1u);
        i = (pb_u8)(i + 1u);
    }
    acc = pb_mix(acc, (pb_u16)(value | ((pb_u16)run << 8)));
}

if (acc != (pb_u16)EXPECTED_CHECKSUM)
    return (int)((acc ^ (pb_u16)EXPECTED_CHECKSUM) | 1u);
return 0;"""
    return render_case(name, body, params, expected)


FAMILIES = {
    family: (family_params, rle_expected, rle_source)
    for family in FAMILY_NAMES
}


def write_case(family: str, variant: int) -> str:
    params_fn, expected_fn, source_fn = FAMILIES[family]
    params = params_fn(family, variant)
    expected = expected_fn(params)
    name = f"{family}_{variant:02d}"
    case_dir = GENERATED / name
    case_dir.mkdir(parents=True, exist_ok=True)
    (case_dir / "main.c").write_text(source_fn(name, params, expected), encoding="utf-8")
    return name


def main() -> None:
    if GENERATED.exists():
        shutil.rmtree(GENERATED)
    GENERATED.mkdir(parents=True, exist_ok=True)

    names: list[str] = []
    for family in FAMILY_NAMES:
        for variant in range(VARIANTS_PER_FAMILY):
            names.append(write_case(family, variant))

    with EXPECTED.open("w", encoding="utf-8") as handle:
        handle.write("benchmark,expected_return\n")
        for name in names:
            handle.write(f"{name},0\n")

    total = len(names)
    print(f"generated {total} portable benchmarks under {GENERATED}")


if __name__ == "__main__":
    main()
